"""
Semantic validator for PrismQL queries.

Goes beyond syntax validation to check if queries produce expected results.
"""

from dataclasses import dataclass
from typing import Any, Optional

from prismql.backends.memory import MemoryBackend
from prismql.engine import PrismQLEngine
from prismql.types import MessageGroup, QueryResult


@dataclass
class SemanticValidationResult:
    """Result of semantic validation."""

    queries_equivalent: bool  # Do they produce the same results?
    generated_result: Optional[QueryResult]
    ground_truth_result: Optional[QueryResult]
    differences: list[str]  # Specific differences found
    semantic_errors: list[str]  # Semantic mistakes (INWIN vs FOLLOWED_BY, etc.)
    notes: list[str]  # Additional observations

    def __str__(self) -> str:
        if self.queries_equivalent:
            return "✓ Queries are semantically equivalent"

        lines = ["✗ Queries produce different results:"]
        for diff in self.differences:
            lines.append(f"  - {diff}")

        if self.semantic_errors:
            lines.append("\nSemantic errors detected:")
            for error in self.semantic_errors:
                lines.append(f"  - {error}")

        if self.notes:
            lines.append("\nNotes:")
            for note in self.notes:
                lines.append(f"  - {note}")

        return "\n".join(lines)


class SemanticValidator:
    """
    Validates semantic correctness of PrismQL queries.

    Executes both generated and ground truth queries on test data
    and compares results to detect semantic differences.
    """

    def __init__(
        self,
        engine: PrismQLEngine,
        verbose: bool = False,
    ):
        """
        Initialize semantic validator.

        Args:
            engine: PrismQL engine to execute queries
            verbose: Whether to print detailed debug info
        """
        self.engine = engine
        self.verbose = verbose

    def validate(
        self,
        generated_query: str,
        ground_truth_query: str,
        description: str = "",
    ) -> SemanticValidationResult:
        """
        Validate semantic correctness of a generated query.

        Args:
            generated_query: The query generated by the LLM
            ground_truth_query: The correct reference query
            description: Natural language description (for context)

        Returns:
            SemanticValidationResult with detailed comparison
        """
        differences = []
        semantic_errors = []
        notes = []

        # Execute both queries
        try:
            gen_result = self.engine.execute(generated_query)
        except Exception as e:
            return SemanticValidationResult(
                queries_equivalent=False,
                generated_result=None,
                ground_truth_result=None,
                differences=[f"Generated query failed to execute: {e}"],
                semantic_errors=[],
                notes=[],
            )

        try:
            gt_result = self.engine.execute(ground_truth_query)
        except Exception as e:
            return SemanticValidationResult(
                queries_equivalent=False,
                generated_result=gen_result,
                ground_truth_result=None,
                differences=[f"Ground truth query failed to execute: {e}"],
                semantic_errors=[],
                notes=["This is likely a bug in the test case!"],
            )

        # Compare results
        if self._results_equal(gen_result, gt_result):
            return SemanticValidationResult(
                queries_equivalent=True,
                generated_result=gen_result,
                ground_truth_result=gt_result,
                differences=[],
                semantic_errors=[],
                notes=[],
            )

        # Results differ - analyze why
        differences = self._analyze_differences(gen_result, gt_result)

        # Detect common semantic errors by analyzing query structure
        semantic_errors = self._detect_semantic_errors(
            generated_query, ground_truth_query, description
        )

        # Add notes about result structure differences
        notes = self._analyze_result_structure(gen_result, gt_result)

        return SemanticValidationResult(
            queries_equivalent=False,
            generated_result=gen_result,
            ground_truth_result=gt_result,
            differences=differences,
            semantic_errors=semantic_errors,
            notes=notes,
        )

    def _normalize_query_structure(self, query: str) -> str:
        """
        Normalize query structure for comparison.

        Handles:
        - Whitespace normalization
        - INWINDOW restriction order (unordered)
        - Quantifier expansion
        """
        import re

        # Normalize whitespace
        query = re.sub(r'\s+', ' ', query.strip())

        # Normalize INWINDOW restriction order (they're unordered)
        # from(alice), from(bob) INWINDOW 5 === from(bob), from(alice) INWINDOW 5
        def sort_inwindow_restrictions(match):
            restrictions = match.group(1)
            window_clause = match.group(2)

            # Split by comma and sort
            parts = [r.strip() for r in restrictions.split(',')]
            parts.sort()

            return 'SELECT ' + ', '.join(parts) + ' ' + window_clause

        query = re.sub(
            r'SELECT\s+(.*?)\s+(INWINDOW\s+\d+)',
            sort_inwindow_restrictions,
            query,
            flags=re.IGNORECASE
        )

        return query

    def _results_equal(self, result1: QueryResult, result2: QueryResult) -> bool:
        """
        Check if two query results are equal.

        Handles different orderings and duplicate handling.
        """
        # Convert to sets of frozensets for order-independent comparison
        def to_comparable(result: QueryResult) -> set:
            return {
                frozenset(sorted(group) if isinstance(group, list) else [group])
                for group in result
            }

        return to_comparable(result1) == to_comparable(result2)

    def _analyze_differences(
        self, gen_result: QueryResult, gt_result: QueryResult
    ) -> list[str]:
        """Analyze specific differences between results."""
        differences = []

        # Count results
        gen_count = len(gen_result)
        gt_count = len(gt_result)

        if gen_count != gt_count:
            differences.append(
                f"Result count mismatch: generated has {gen_count}, expected {gt_count}"
            )

        # Find missing and extra results
        gen_set = {
            frozenset(sorted(group) if isinstance(group, list) else [group])
            for group in gen_result
        }
        gt_set = {
            frozenset(sorted(group) if isinstance(group, list) else [group])
            for group in gt_result
        }

        missing = gt_set - gen_set
        extra = gen_set - gt_set

        if missing:
            differences.append(
                f"Missing {len(missing)} expected results: {list(missing)[:3]}..."
                if len(missing) > 3
                else f"Missing results: {list(missing)}"
            )

        if extra:
            differences.append(
                f"Has {len(extra)} unexpected results: {list(extra)[:3]}..."
                if len(extra) > 3
                else f"Extra results: {list(extra)}"
            )

        return differences

    def _detect_semantic_errors(
        self, generated: str, ground_truth: str, description: str
    ) -> list[str]:
        """
        Detect common semantic errors by analyzing query patterns.

        Checks for:
        - INWIN vs FOLLOWED_BY confusion
        - Pattern variable misuse
        - Quantifier errors
        - Operator precedence issues
        """
        errors = []

        gen_lower = generated.lower()
        gt_lower = ground_truth.lower()
        desc_lower = description.lower()

        # Check INWIN vs FOLLOWED_BY confusion
        if "inwin" in gen_lower and "followed_by" in gt_lower:
            if any(
                word in desc_lower
                for word in ["then", "followed by", "after", "before", "sequence"]
            ):
                errors.append(
                    "Used INWIN (unordered) but description suggests FOLLOWED_BY (ordered sequence)"
                )

        if "followed_by" in gen_lower and "inwin" in gt_lower:
            if any(word in desc_lower for word in ["together", "within", "co-occur"]):
                errors.append(
                    "Used FOLLOWED_BY (ordered) but description suggests INWIN (unordered co-occurrence)"
                )

        # Check pattern variable usage
        gen_vars = self._extract_pattern_variables(generated)
        gt_vars = self._extract_pattern_variables(ground_truth)

        if len(gen_vars) != len(gt_vars):
            errors.append(
                f"Pattern variable count mismatch: generated has {len(gen_vars)}, expected {len(gt_vars)}"
            )

        # Check quantifiers
        # Note: from($user){2} should be semantically equivalent to from($user), from($user)
        # but has a known bug causing different result counts. Don't penalize LLM for this.
        gen_quants = self._extract_quantifiers(generated)
        gt_quants = self._extract_quantifiers(ground_truth)

        # Normalize both queries to expand quantifiers for comparison
        import re
        gen_normalized = re.sub(r'from\(\$\w+\)\{2\}', lambda m: m.group(0).replace('{2}', '') + ', ' + m.group(0).replace('{2}', ''), generated)
        gt_normalized = re.sub(r'from\(\$\w+\)\{2\}', lambda m: m.group(0).replace('{2}', '') + ', ' + m.group(0).replace('{2}', ''), ground_truth)

        gen_normalized = re.sub(r'from\(\$user\)\{2\}', 'from($user), from($user)', gen_normalized)
        gt_normalized = re.sub(r'from\(\$user\)\{2\}', 'from($user), from($user)', gt_normalized)

        # Extract quantifiers from normalized queries
        gen_quants_norm = self._extract_quantifiers(gen_normalized)
        gt_quants_norm = self._extract_quantifiers(gt_normalized)

        if gen_quants_norm != gt_quants_norm and gt_quants_norm:
            errors.append(
                f"Quantifier mismatch: generated has {gen_quants}, expected {gt_quants}"
            )

        return errors

    def _extract_pattern_variables(self, query: str) -> list[str]:
        """Extract pattern variables like $user, $asker from query."""
        import re

        return re.findall(r"\$\w+", query)

    def _extract_quantifiers(self, query: str) -> list[str]:
        """Extract quantifiers like {2}, {3} from query."""
        import re

        return re.findall(r"\{\d+\}", query)

    def _analyze_result_structure(
        self, gen_result: QueryResult, gt_result: QueryResult
    ) -> list[str]:
        """Analyze structural differences in results."""
        notes = []

        if not gen_result and gt_result:
            notes.append("Generated query returned no results (empty set)")

        if gen_result and not gt_result:
            notes.append(
                "Generated query returned results but expected empty (may be too broad)"
            )

        # Check if results are message groups (lists) vs individual messages
        if gen_result and gt_result:
            gen_has_groups = any(isinstance(g, list) and len(g) > 1 for g in gen_result)
            gt_has_groups = any(isinstance(g, list) and len(g) > 1 for g in gt_result)

            if gen_has_groups and not gt_has_groups:
                notes.append(
                    "Generated query returns message groups, expected individual messages"
                )
            elif not gen_has_groups and gt_has_groups:
                notes.append(
                    "Generated query returns individual messages, expected message groups"
                )

            # Check group sizes
            if gen_has_groups and gt_has_groups:
                gen_sizes = {len(g) if isinstance(g, list) else 1 for g in gen_result}
                gt_sizes = {len(g) if isinstance(g, list) else 1 for g in gt_result}

                if gen_sizes != gt_sizes:
                    notes.append(
                        f"Message group size mismatch: generated has sizes {gen_sizes}, expected {gt_sizes}"
                    )

        return notes


def create_test_data_for_case(test_case: Any) -> list[dict[str, Any]]:
    """
    Create realistic test data for a specific test case.

    Generates messages that will produce meaningful results for the query.
    """
    from random import randint

    messages = []
    msg_id = 1

    # Add baseline messages
    users = ["alice", "bob", "charlie", "customer", "support", "manager"]

    # Add varied messages to trigger different query patterns
    test_patterns = [
        # Greetings
        {"user": "alice", "text": "hello everyone"},
        {"user": "bob", "text": "hi there"},
        {"user": "support", "text": "hey, how can I help?"},
        # Questions
        {"user": "customer", "text": "how do I fix this error?"},
        {"user": "alice", "text": "what is the issue here?"},
        # Problems
        {"user": "customer", "text": "I have a bug in the system"},
        {"user": "bob", "text": "there is an error message"},
        # Solutions
        {"user": "support", "text": "here is the solution"},
        {"user": "support", "text": "this should be fixed now"},
        # Thanks
        {"user": "customer", "text": "thank you so much!"},
        {"user": "alice", "text": "thanks for the help"},
        # Regular messages
        {"user": "charlie", "text": "random message here"},
        {"user": "manager", "text": "checking in on progress"},
        # Sequential patterns
        {"user": "customer", "text": "urgent problem here"},
        {"user": "support", "text": "let me resolve that"},
        {"user": "customer", "text": "appreciate it"},
    ]

    for i, pattern in enumerate(test_patterns, start=1):
        messages.append({"id": i, **pattern})

    # Add more filler messages
    for i in range(len(test_patterns) + 1, 50):
        messages.append(
            {
                "id": i,
                "user": users[randint(0, len(users) - 1)],
                "text": f"message {i}",
            }
        )

    return messages
